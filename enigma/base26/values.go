//------------------------------------------------------------------------------

// a - number of values (4 bits)
// b - number of values (5 bits)
// m - min value for 4 bits

// N - total values (base)

// N = a + b
// 2*a + b = 2^5

// b = 2 * (2^4 - a) =  2^5 - 2*a = 2*N - 2^5

// N = a + b = a + (2^5 - 2*a) = 2^5 - a

// a = 2^5 - N
// b = 2*N - 2^5 = 2*m
// m = 2^4 - a = N - 2^4 = b/2

//------------------------------------------------------------------------------

// base 26:
// N = 26
// a = 2^5 - N = 32 - 26 = 6
// b = 2*N - 2^5 = 2*26 - 32 = 20
// m = N - 2^4 = 26 - 16 = 10

//------------------------------------------------------------------------------

